-- Deploy tet:webhooks/outbox to pg

BEGIN;

-- @nestjs/outbox: PostgresOutboxStore's schema "nest_outbox", from version 0 to 1.
-- Run it in one transaction.

CREATE SCHEMA IF NOT EXISTS "nest_outbox";

CREATE TABLE IF NOT EXISTS "nest_outbox".migrations (
  version integer PRIMARY KEY,
  name text NOT NULL,
  applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE "nest_outbox".messages (
  seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id text NOT NULL UNIQUE,
  topic text NOT NULL,
  payload jsonb,
  headers jsonb NOT NULL,
  key text,
  created_at bigint NOT NULL,
  available_at bigint NOT NULL,
  attempts integer NOT NULL DEFAULT 0,
  last_error text,
  history jsonb NOT NULL DEFAULT '[]',
  lease_owner text,
  lease_until bigint
);

CREATE TABLE "nest_outbox".dead_letters (
  id text PRIMARY KEY,
  seq bigint NOT NULL,
  topic text NOT NULL,
  payload jsonb,
  headers jsonb NOT NULL,
  key text,
  created_at bigint NOT NULL,
  attempts integer NOT NULL,
  last_error text,
  history jsonb NOT NULL,
  reason text NOT NULL,
  failed_at bigint NOT NULL
);

CREATE TABLE "nest_outbox".inbox (
  consumer text NOT NULL,
  message_id text NOT NULL,
  processed_at bigint NOT NULL,
  PRIMARY KEY (consumer, message_id)
);

CREATE INDEX messages_key_seq ON "nest_outbox".messages (key, seq) WHERE key IS NOT NULL;

CREATE INDEX dead_letters_topic_failed_at ON "nest_outbox".dead_letters (topic, failed_at);

CREATE INDEX inbox_processed_at ON "nest_outbox".inbox (processed_at);

INSERT INTO "nest_outbox".migrations (version, name) VALUES (1, 'initial');

REVOKE ALL ON SCHEMA nest_outbox FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA nest_outbox TO postgres, service_role;
REVOKE ALL ON ALL TABLES IN SCHEMA nest_outbox FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA nest_outbox FROM PUBLIC, anon, authenticated;
GRANT SELECT ON nest_outbox.migrations TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON nest_outbox.messages, nest_outbox.dead_letters, nest_outbox.inbox TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA nest_outbox TO service_role;

ALTER TABLE nest_outbox.migrations ENABLE ROW LEVEL SECURITY;
ALTER TABLE nest_outbox.messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE nest_outbox.dead_letters ENABLE ROW LEVEL SECURITY;
ALTER TABLE nest_outbox.inbox ENABLE ROW LEVEL SECURITY;
CREATE POLICY service_role_read ON nest_outbox.migrations FOR SELECT TO service_role USING (true);
CREATE POLICY service_role_access ON nest_outbox.messages TO service_role USING (true) WITH CHECK (true);
CREATE POLICY service_role_access ON nest_outbox.dead_letters TO service_role USING (true) WITH CHECK (true);
CREATE POLICY service_role_access ON nest_outbox.inbox TO service_role USING (true) WITH CHECK (true);

-- Persisted pending messages must remain publishable, including after a Redis loss.
INSERT INTO nest_outbox.messages (id, topic, payload, headers, key, created_at, available_at)
SELECT m.id::text, c.entity_type, jsonb_build_object('messageId', m.id::text),
       '{}'::jsonb, m.configuration_ref,
       floor(extract(epoch FROM m.created_at) * 1000)::bigint,
       floor(extract(epoch FROM now()) * 1000)::bigint
FROM webhooks.webhook_message AS m
JOIN webhooks.webhook_configuration AS c ON c.ref = m.configuration_ref
WHERE m.status = 'pending'
ORDER BY m.created_at, m.id;

COMMIT;
